CREATE DATABASE IF NOT EXISTS `siam_stories` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `siam_stories`;

-- --------------------------------------------------------
-- 1. ตาราง admins: สำหรับจัดการผู้ดูแลระบบ
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS `admins` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `username` VARCHAR(50) NOT NULL UNIQUE,
  `email` VARCHAR(100) NULL UNIQUE,
  `password_hash` VARCHAR(255) NOT NULL,
  `display_name` VARCHAR(100) NOT NULL,
  `role` ENUM('admin', 'member') NOT NULL DEFAULT 'member',
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- --------------------------------------------------------
-- 2. ตาราง traditions: ข้อมูลประเพณีไทย 4 ภาค
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS `traditions` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `name` VARCHAR(255) NOT NULL,
  `region` ENUM('north', 'isan', 'central', 'south') NOT NULL,
  `province` VARCHAR(255) NOT NULL,
  `detail` TEXT NOT NULL,
  `image` VARCHAR(255) NOT NULL,
  `sort_order` INT NOT NULL DEFAULT 0,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  INDEX `idx_traditions_region` (`region`),
  INDEX `idx_traditions_sort` (`sort_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- --------------------------------------------------------
-- 3. ตาราง tradition_months: ความสัมพันธ์ประเพณีกับเดือนที่จัดงาน (1-12)
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS `tradition_months` (
  `tradition_id` INT UNSIGNED NOT NULL,
  `month` TINYINT UNSIGNED NOT NULL,
  PRIMARY KEY (`tradition_id`, `month`),
  INDEX `idx_tm_month` (`month`),
  CONSTRAINT `fk_tradition_months_tradition` FOREIGN KEY (`tradition_id`) REFERENCES `traditions` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- --------------------------------------------------------
-- 4. ตาราง foods: ข้อมูลอาหารท้องถิ่น 4 ภาค
-- --------------------------------------------------------
CREATE TABLE IF NOT EXISTS `foods` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `name` VARCHAR(255) NOT NULL,
  `region` ENUM('north', 'isan', 'central', 'south') NOT NULL,
  `detail` TEXT NOT NULL,
  `image` VARCHAR(255) NOT NULL,
  `tags` VARCHAR(255) NOT NULL COMMENT 'ป้ายกำกับคั่นด้วยจุลภาค',
  `sort_order` INT NOT NULL DEFAULT 0,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  INDEX `idx_foods_region` (`region`),
  INDEX `idx_foods_sort` (`sort_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

